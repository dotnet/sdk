"""Refresh the temporary, offline-buildable ORAS source dependency from a local checkout."""
import argparse
import json
from pathlib import Path
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("repository", type=Path)
parser.add_argument("commit", help="Full reviewed ORAS commit SHA")
args = parser.parse_args()
if not re.fullmatch(r"[0-9a-f]{40}", args.commit):
    parser.error("commit must be a full lowercase 40-character SHA")


def git(*arguments):
    return subprocess.check_output(["git", "-C", str(args.repository), *arguments])


resolved = git("rev-parse", "--verify", args.commit + "^{commit}").decode().strip()
if resolved != args.commit:
    parser.error("commit did not resolve to the supplied SHA")
root = Path(__file__).resolve().parents[1]
project = root / "src/Containers/OrasProject.Oras.SourceBuild"
source = project / "Source"
files = {}
entries = []
for row in git("ls-tree", "-r", args.commit, "src/OrasProject.Oras/").decode().splitlines():
    metadata, path = row.split("\t", 1)
    if not path.endswith(".cs"):
        continue
    blob = metadata.split()[2]
    relative = Path(path).relative_to("src/OrasProject.Oras")
    content = git("show", f"{args.commit}:{path}").removeprefix(b"\xef\xbb\xbf")
    url = f"https://github.com/jetersen/oras-dotnet/blob/{args.commit}/{path}"
    files[relative] = f"// Copied from {url}\n".encode() + content
    entries.append({
        "id": "oras-" + str(relative.with_suffix("")).replace("/", "-").lower(),
        "local_path": str((source / relative).relative_to(root)),
        "notes": "Temporary ORAS source dependency; generated by eng/update-oras-source.py. Only a provenance header is added.",
        "area_labels": ["Area-Containers"],
        "sources": [{"repo": "jetersen/oras-dotnet", "ref": "feature/token-http-client",
                     "path": path, "baseline_ref_sha": args.commit, "baseline_blob_sha": blob}],
    })
if not files:
    parser.error("commit contains no ORAS library C# sources")
# Remove only obsolete generated C# files in this dependency's dedicated source directory.
for existing in source.rglob("*.cs"):
    if existing.relative_to(source) not in files:
        existing.unlink()
for relative, content in files.items():
    destination = source / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(content)
manifest_path = root / "eng/vendored-files.json"
manifest = json.loads(manifest_path.read_text())
manifest["$comment"] = "Manifest of vendored sources. See eng/vendored-files.md. Includes shared Microsoft.Testing.Platform sources and the temporary ORAS.NET source dependency."
manifest["$comment_labels"] = "Entries outside the default dotnet test area must set area_labels explicitly."
manifest["entries"] = [entry for entry in manifest["entries"] if not entry["id"].startswith("oras-")] + entries
manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
(project / "LICENSE").write_bytes(git("show", f"{args.commit}:LICENSE"))
(project / "SourceVersion.props").write_text(
    '<!-- Generated by eng/update-oras-source.py. Do not edit. -->\n'
    '<Project>\n  <PropertyGroup>\n'
    f'    <OrasSourceCommit>{args.commit}</OrasSourceCommit>\n'
    '  </PropertyGroup>\n</Project>\n')
print(f"Copied {len(files)} source files from {args.commit}")
